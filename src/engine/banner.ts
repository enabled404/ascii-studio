const UNKNOWN_GLYPH: Glyph = ['#####', '#...#', '#...#', '#...#', '#####']

function outlineGlyph(g: Glyph): Glyph {
  const rows = g.length
  const cols = g[0]?.length || 5
  const out: string[] = []
  for (let y = 0; y < rows; y++) {
    let row = ''
    for (let x = 0; x < cols; x++) {
      if (g[y][x] !== '#') {
        row += '.'
        continue
      }
      const neighbours = [
        [x - 1, y], [x + 1, y], [x, y - 1], [x, y + 1],
      ]
      const isEdge = neighbours.some(([nx, ny]) => nx < 0 || nx >= cols || ny < 0 || ny >= rows || g[ny][nx] !== '#')
      row += isEdge ? '#' : '.'
    }
    out.push(row)
  }
  return out
}

export function renderBanner(
  text: string,
  style: BannerStyle = 'block',
  fillChar = '#',
  font: BannerFont = 'standard',
): string {
  const safeFill = fillChar || '#'
  const upper = text.toUpperCase()
  const fontDict = font === 'mini' ? FONT_MINI : font === 'isometric' ? FONT_ISOMETRIC : font === 'digital' ? FONT_DIGITAL : FONT_STANDARD

  if (font === 'isometric' || font === 'digital') {
    // Multi-line pre-formatted glyphs
    const glyphs = upper.split('').map((c) => fontDict[c] ?? fontDict[' '] ?? ['   ', '   ', '   '])
    const numRows = Math.max(...glyphs.map((g) => g.length), 3)
    const lines: string[] = []
    for (let y = 0; y < numRows; y++) {
      let line = ''
      glyphs.forEach((g, gi) => {
        line += g[y] ?? ' '.repeat(g[0]?.length || 3)
        if (gi < glyphs.length - 1) line += ' '
      })
      lines.push(line)
    }
    return lines.join('\n')
  }

  const chars = upper.split('')
  const glyphs = chars.map((c) => fontDict[c] ?? (font === 'mini' ? ['###', '#.#', '###'] : UNKNOWN_GLYPH))
  const styled = glyphs.map((g) => (style === 'outline' || style === 'neon' ? outlineGlyph(g) : g))
  const on = style === 'dots' ? '●'
    : style === 'stars' ? '★'
    : style === 'double' ? '▓'
    : style === 'cyber' ? 'Ξ'
    : style === 'neon' ? '░'
    : safeFill

  const off = ' '
  const numRows = styled[0]?.length || 5
  const rows: string[] = []

  for (let y = 0; y < numRows; y++) {
    let line = ''
    styled.forEach((g, gi) => {
      const slant = style === 'slant' ? y : 0
      line += ' '.repeat(slant)
      const glyphW = g[y]?.length || 5
      for (let x = 0; x < glyphW; x++) {
        line += g[y]?.[x] === '#' ? on : off
      }
      if (gi < styled.length - 1) line += ' '
    })
    rows.push(line.replace(/\s+$/, ''))
  }

  if (style === 'shadow') {
    const shadow: string[] = []
    for (let i = 0; i < rows.length; i++) {
      shadow.push(rows[i])
      if (i < rows.length - 1) {
        shadow.push('  ' + rows[i].split(safeFill).join('·'))
      }
    }
    return shadow.join('\n')
  }

  return rows.join('\n')
}

export function frameBanner(banner: string, border: BorderStyle): string {
  if (border === 'none') return banner
  const lines = banner.split('\n')
  const maxW = Math.max(...lines.map((l) => l.length), 0)
  const pad = 2

  let tl = '+', tr = '+', bl = '+', br = '+', h = '-', v = '|'
  if (border === 'double') {
    tl = '╔'; tr = '╗'; bl = '╚'; br = '╝'; h = '═'; v = '║'
  } else if (border === 'rounded') {
    tl = '╭'; tr = '╮'; bl = '╰'; br = '╯'; h = '─'; v = '│'
  } else if (border === 'single') {
    tl = '┌'; tr = '┐'; bl = '└'; br = '┘'; h = '─'; v = '│'
  } else if (border === 'stars') {
    tl = '*'; tr = '*'; bl = '*'; br = '*'; h = '*'; v = '*'
  } else if (border === 'hash') {
    tl = '#'; tr = '#'; bl = '#'; br = '#'; h = '#'; v = '#'
  } else if (border === 'cyber') {
    tl = '◤'; tr = '◥'; bl = '◣'; br = '◢'; h = '━'; v = '┃'
  } else if (border === 'bold') {
    tl = '█'; tr = '█'; bl = '█'; br = '█'; h = '▀'; v = '█'
  }

  const innerW = maxW + pad * 2
  const top = tl + h.repeat(innerW) + tr
  const bottom = bl + h.repeat(innerW) + br
  const middle = lines.map((line) => {
    const trailing = ' '.repeat(Math.max(0, maxW - line.length))
    return v + ' '.repeat(pad) + line + trailing + ' '.repeat(pad) + v
  })

  return [top, ...middle, bottom].join('\n')
}

